# 19. Torsors and Principal G-Sheaves (SH-19)
# ==============================================================================


@dataclass
class PrincipalBundleZ2:
    """A Z_2-torsor on a simplicial complex, classified by H^1(X, Z_2).
    Holonomy around closed loops is in {+1, -1}.
    """

    cover: List[OpenSet]
    transition_signs: Dict[Tuple[int, int], int]  # +1 or -1

    def holonomy_around_loop(self, loop_indices: List[int]) -> int:
        """Compute prod_{i} g_{i, i+1}."""
        holo = 1
        for k in range(len(loop_indices)):
            i = loop_indices[k]
            j = loop_indices[(k + 1) % len(loop_indices)]
            pair = (min(i, j), max(i, j))
            sign = self.transition_signs.get(pair, 1)
            holo *= sign
        return holo

    @property
    def is_trivial_bundle(self) -> bool:
        """Trivial iff all transition signs can be trivialized (holonomy == +1 on all loops)."""
        loop = list(range(len(self.cover)))
        return self.holonomy_around_loop(loop) == 1


