# 8. Equalizer Diagram of a Sheaf (SH-08)
# ==============================================================================


def compute_equalizer_kernel(
    presheaf: Presheaf[T], u: OpenSet, cover: List[OpenSet]
) -> List[Tuple[T, ...]]:
    """Compute the equalizer:
    eq = { (s_i) in prod F(U_i) | rho(s_i) == rho(s_j) on U_i cap U_j }.
    """
    cover_secs = [presheaf.sections(u_i) for u_i in cover]
    import itertools

    matching_tuples = []
    for family in itertools.product(*cover_secs):
        compat = True
        for i in range(len(cover)):
            for j in range(i + 1, len(cover)):
                u_ij = cover[i].intersection(cover[j])
                if u_ij.is_empty:
                    continue
                if presheaf.restrict(cover[i], u_ij, family[i]) != presheaf.restrict(
                    cover[j], u_ij, family[j]
                ):
                    compat = False
                    break
            if not compat:
                break
        if compat:
            matching_tuples.append(family)
    return matching_tuples


# ==============================================================================
# 9. Plus Construction F^+ (SH-09)
# ==============================================================================


def plus_construction(presheaf: Presheaf[T]) -> Presheaf[Tuple[T, ...]]:
    """Grothendieck's plus functor F^+(U) = H^0_cech(U, F).
    Each section is an equivalence class of matching families over covers.
    """
    plus_sections: Dict[OpenSet, List[Tuple[T, ...]]] = {}
    for u in presheaf.sections_map.keys():
        # For minimal open sets U_x, F^+(U_x) ~ F(U_x)
        pts = sorted(list(u.elements))
        pt_opens = [presheaf.topology.minimal_open_neighborhood(p) for p in pts]
        eq = compute_equalizer_kernel(presheaf, u, pt_opens)
        plus_sections[u] = eq

    def plus_restrict(u: OpenSet, v: OpenSet, s: Tuple[T, ...]) -> Tuple[T, ...]:
        pts_u = sorted(list(u.elements))
        pts_v = sorted(list(v.elements))
        idx_map = [pts_u.index(p) for p in pts_v]
        return tuple(s[i] for i in idx_map)

    return Presheaf(
        name=f"{presheaf.name}^+",
        topology=presheaf.topology,
        sections_map=plus_sections,
        restriction_op=plus_restrict,
    )


# ==============================================================================
# 10. Sheafification Functor F^# (SH-10)
# ==============================================================================


def sheafify(presheaf: Presheaf[T]) -> Presheaf[Tuple[T, ...]]:
    """Sheafification F^# = (F^+)^+.
    Transforms any presheaf into an authentic sheaf while preserving stalks.
    """
    f_plus = plus_construction(presheaf)
    f_sharp = plus_construction(f_plus)
    # Flatten sections
    flat_sections: Dict[OpenSet, List[Any]] = {}
    for u, secs in f_sharp.sections_map.items():
        flat_sections[u] = secs
    return Presheaf(
        name=f"{presheaf.name}^#",
        topology=presheaf.topology,
        sections_map=flat_sections,
        restriction_op=f_sharp.restriction_op,
    )


