@dataclass
class StructureSheaf:
    """Structure sheaf O_X assigning rings of rational piecewise-constant functions."""

    topology: PosetTopology

    def sections(self, u: OpenSet) -> List[Tuple[Fraction, ...]]:
        """Sections over U are rational coordinate vectors on the simplices in U."""
        k = len(u.elements)
        zero = tuple(Fraction(0) for _ in range(k))
        basis = [zero]
        for i in range(k):
            vec = [Fraction(0)] * k
            vec[i] = Fraction(1)
            basis.append(tuple(vec))
        return basis


