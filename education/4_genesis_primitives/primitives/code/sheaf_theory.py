# 3. Stalk at a Simplex/Point (SH-03)
# ==============================================================================


@dataclass(frozen=True)
class Germ(Generic[T]):
    """A germ of a section at point x: equivalence class [(U, s)]_x."""

    point: str
    neighborhood: OpenSet
    section: T


def compute_stalk(presheaf: Presheaf[T], x: str) -> List[Germ[T]]:
    """In a finite Alexandrov poset, the stalk F_x is canonically isomorphic
    to the sections over the minimal open neighborhood U_x.
    """
    u_x = presheaf.topology.minimal_open_neighborhood(x)
    secs = presheaf.sections(u_x)
    return [Germ(point=x, neighborhood=u_x, section=s) for s in secs]


