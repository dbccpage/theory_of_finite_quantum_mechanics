# 11. Constant Sheaf vs Constant Presheaf (SH-11)
# ==============================================================================


def make_constant_presheaf(topology: PosetTopology, val: str) -> Presheaf[str]:
    """Constant presheaf assigns val to EVERY open set, including disconnected ones.
    Fails S2 on disjoint unions U = U1 uplus U2!
    """
    sections = {u: [val] for u in [OpenSet(frozenset(s)) for s in [set(), topology.base_elements]]}
    for p in topology.base_elements:
        u_p = topology.minimal_open_neighborhood(p)
        sections[u_p] = [val]

    return Presheaf(
        name="ConstantPresheaf",
        topology=topology,
        sections_map=sections,
        restriction_op=lambda u, v, s: s,
    )


def make_constant_sheaf(topology: PosetTopology, val: str) -> Presheaf[Tuple[str, ...]]:
    """Constant sheaf assigns locally constant functions (one val per connected component)."""
    cp = make_constant_presheaf(topology, val)
    return plus_construction(cp)


