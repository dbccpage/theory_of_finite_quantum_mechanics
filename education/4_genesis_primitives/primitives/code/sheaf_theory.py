# ==============================================================================
# 1. Poset Open Set Category & Alexandrov Topology (SH-01)
# ==============================================================================


@dataclass(frozen=True)
class OpenSet:
    """An open set in the Alexandrov topology of a finite poset / simplicial complex.

    For a simplicial complex K, open sets in the face poset are up-sets:
    if simplex sigma in U and tau contains sigma, then tau in U (stars of subcomplexes).
    """

    elements: FrozenSet[str]

    def __contains__(self, item: str) -> bool:
        return item in self.elements

    def is_subset(self, other: "OpenSet") -> bool:
        return self.elements.issubset(other.elements)

    def union(self, other: "OpenSet") -> "OpenSet":
        return OpenSet(self.elements | other.elements)

    def intersection(self, other: "OpenSet") -> "OpenSet":
        return OpenSet(self.elements & other.elements)

    @property
    def is_empty(self) -> bool:
        return len(self.elements) == 0

    def __repr__(self) -> str:
        elems = sorted(list(self.elements))
        return f"OpenSet({elems})"


@dataclass
class PosetTopology:
    """Alexandrov topology generated by a finite poset or simplicial complex."""

    base_elements: FrozenSet[str]
    # Poset relation: x <= y means y is in the closure or star of x
    le_relation: FrozenSet[Tuple[str, str]]

    def minimal_open_neighborhood(self, x: str) -> OpenSet:
        """The minimal open set containing x: U_x = {y | x <= y} (the star)."""
        star = {y for (a, y) in self.le_relation if a == x}
        star.add(x)
        return OpenSet(frozenset(star))

    def is_open(self, u: OpenSet) -> bool:
        """Check if U is an up-set: x in U and x <= y => y in U."""
        for x in u.elements:
            for a, y in self.le_relation:
                if a == x and y not in u.elements:
                    return False
        return True


# ==============================================================================
# 2. Presheaf Functor (SH-02)
# ==============================================================================


@dataclass
class Presheaf(Generic[T]):
    """A presheaf F: Open(X)^op -> Set (or Vect).

    Assigns:
    - F(U): set of sections over U
    - rho^U_V: F(U) -> F(V) for V subset U (restriction map)
    """

    name: str
    topology: PosetTopology
    # Map from OpenSet to collection of sections
    sections_map: Dict[OpenSet, List[T]]
    # Restriction operator: (U, V, section) -> restricted section
    restriction_op: Callable[[OpenSet, OpenSet, T], T]

    def sections(self, u: OpenSet) -> List[T]:
        return self.sections_map.get(u, [])

    def restrict(self, u: OpenSet, v: OpenSet, s: T) -> T:
        """Apply restriction rho^U_V(s). Verifies V subset U."""
        if not v.is_subset(u):
            raise ValueError(f"Cannot restrict: {v} is not a subset of {u}")
        if u == v:
            return s
        return self.restriction_op(u, v, s)

    def check_functoriality(self, u: OpenSet, v: OpenSet, w: OpenSet, s: T) -> bool:
        """Verify rho^V_W(rho^U_V(s)) == rho^U_W(s) for W subset V subset U."""
        if not (w.is_subset(v) and v.is_subset(u)):
            return False
        res_uv = self.restrict(u, v, s)
        res_vw = self.restrict(v, w, res_uv)
        res_uw = self.restrict(u, w, s)
        return res_vw == res_uw


