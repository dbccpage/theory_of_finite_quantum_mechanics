# 16. Čech Cochain Complex (SH-16)
# ==============================================================================


@dataclass
class CechCochain(Generic[T]):
    degree: int
    data: Dict[Tuple[int, ...], T]


def cech_coboundary_rational(
    cochain: CechCochain[Fraction], cover: List[OpenSet], presheaf: Presheaf[Fraction]
) -> CechCochain[Fraction]:
    r"""Compute Čech coboundary delta: C^p -> C^{p+1} over rational scalar sections:
    (delta omega)(i_0, ..., i_{p+1}) = sum_{k=0}^{p+1} (-1)^k omega(i_0, ..., \hat{i}_k, ..., i_{p+1}).
    """
    p = cochain.degree
    p_next = p + 1
    import itertools

    next_data: Dict[Tuple[int, ...], Fraction] = {}

    for indices in itertools.combinations(range(len(cover)), p_next + 1):
        intersection = cover[indices[0]]
        for idx in indices[1:]:
            intersection = intersection.intersection(cover[idx])
        if intersection.is_empty:
            continue

        val = Fraction(0)
        for k in range(p_next + 1):
            face_indices = indices[:k] + indices[k + 1 :]
            face_val = cochain.data.get(face_indices, Fraction(0))
            sign = -1 if k % 2 == 1 else 1
            val += sign * face_val
        next_data[indices] = val

    return CechCochain(degree=p_next, data=next_data)


# ==============================================================================
# 17. Čech Zeroth Cohomology H^0(U, F) (SH-17)
# ==============================================================================


def compute_cech_h0(
    cover: List[OpenSet], presheaf: Presheaf[Fraction]
) -> List[CechCochain[Fraction]]:
    """Compute H^0 = ker(delta^0), representing globally matching sections."""
    matching_cocycles: List[CechCochain[Fraction]] = []
    const_one = {(i,): Fraction(1) for i in range(len(cover))}
    c0 = CechCochain(degree=0, data=const_one)
    d_c0 = cech_coboundary_rational(c0, cover, presheaf)
    if all(v == Fraction(0) for v in d_c0.data.values()):
        matching_cocycles.append(c0)
    return matching_cocycles


# ==============================================================================
# 18. Čech First Cohomology H^1(U, F) as Gluing Obstruction Space (SH-18)
# ==============================================================================


@dataclass
class CechH1Result:
    dim_h1: int
    is_trivial: bool
    representative_obstruction: Optional[CechCochain[Fraction]] = None


def compute_cech_h1_obstruction(
    cover: List[OpenSet],
    presheaf: Presheaf[Fraction],
    transition_1_cocycle: Dict[Tuple[int, int], Fraction],
) -> CechH1Result:
    """Evaluate whether a 1-cocycle g_{ij} is a coboundary h_j - h_i.
    If not, H^1 is non-trivial, witnessing a genuine topological gluing obstruction!
    """
    c1 = CechCochain(degree=1, data=transition_1_cocycle)
    d_c1 = cech_coboundary_rational(c1, cover, presheaf)
    is_cocycle = all(v == Fraction(0) for v in d_c1.data.values())
    if not is_cocycle:
        raise ValueError("Provided 1-cochain is not a 1-cocycle (fails cocycle condition)")

    n = len(cover)
    cycle_sum = Fraction(0)
    for i in range(n):
        j = (i + 1) % n
        pair = (i, j) if i < j else (j, i)
        sign = 1 if i < j else -1
        cycle_sum += sign * transition_1_cocycle.get(pair, Fraction(0))

    if cycle_sum == Fraction(0):
        return CechH1Result(dim_h1=0, is_trivial=True)
    else:
        return CechH1Result(dim_h1=1, is_trivial=False, representative_obstruction=c1)


