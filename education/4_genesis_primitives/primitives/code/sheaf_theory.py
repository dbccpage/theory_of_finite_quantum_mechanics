# 22. Soft / Fine Sheaf & Partitions of Unity (SH-22)
# ==============================================================================


@dataclass
class PartitionOfUnity:
    """A discrete partition of unity subordinate to cover {U_i}: sum_i phi_i(x) = 1."""

    cover: List[OpenSet]
    weights: Dict[Tuple[int, str], Fraction]

    def verify_sum_to_one(self, points: FrozenSet[str]) -> bool:
        for p in points:
            tot = sum(self.weights.get((i, p), Fraction(0)) for i in range(len(self.cover)))
            if tot != Fraction(1):
                return False
        return True


