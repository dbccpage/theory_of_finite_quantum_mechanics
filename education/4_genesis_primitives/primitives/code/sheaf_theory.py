# 21. Flasque (Injective) Sheaf (SH-21)
# ==============================================================================


def is_flasque_sheaf(presheaf: Presheaf[T], all_open_pairs: List[Tuple[OpenSet, OpenSet]]) -> bool:
    """A sheaf F is flasque if all restriction maps rho^U_V: F(U) -> F(V) are surjective."""
    for u, v in all_open_pairs:
        if v.is_subset(u):
            u_secs = presheaf.sections(u)
            v_secs = presheaf.sections(v)
            restricted_v = {presheaf.restrict(u, v, s) for s in u_secs}
            if not set(v_secs).issubset(restricted_v):
                return False
    return True


