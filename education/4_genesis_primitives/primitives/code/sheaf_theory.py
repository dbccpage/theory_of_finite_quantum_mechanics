# 23. Grothendieck Pretopology on Poset (SH-23)
# ==============================================================================


@dataclass
class GrothendieckSite:
    """A site (C, J) where C is the poset category and J is a Grothendieck pretopology."""

    topology: PosetTopology

    def is_covering_sieve(self, u: OpenSet, family: List[OpenSet]) -> bool:
        """Check pretopology axioms:
        1. Maximality: {U} is a covering of U.
        2. Stability: if {U_i} covers U and V subset U, then {U_i cap V} covers V.
        3. Transitivity: covers of covers are covers.
        """
        union_elems = set()
        for f in family:
            if not f.is_subset(u):
                return False
            union_elems.update(f.elements)
        return union_elems == set(u.elements)


