# 12. Skyscraper Sheaf (SH-12)
# ==============================================================================


def make_skyscraper_sheaf(topology: PosetTopology, point: str, stalk_value: str) -> Presheaf[str]:
    """Skyscraper sheaf i_{x*} A: F(U) = {stalk_value} if point in U else {'0'}."""
    sections: Dict[OpenSet, List[str]] = {}
    all_opens = [OpenSet(frozenset())]
    for p in topology.base_elements:
        all_opens.append(topology.minimal_open_neighborhood(p))
    all_opens.append(OpenSet(topology.base_elements))

    for u in all_opens:
        if point in u.elements:
            sections[u] = [stalk_value]
        else:
            sections[u] = ["0"]

    def sky_restrict(u: OpenSet, v: OpenSet, s: str) -> str:
        if point in v.elements:
            return s
        return "0"

    return Presheaf(
        name=f"Skyscraper_{point}",
        topology=topology,
        sections_map=sections,
        restriction_op=sky_restrict,
    )


# ==============================================================================
# 13. Direct Image Sheaf (Pushforward f_*) (SH-13)
# ==============================================================================


def pushforward_sheaf(
    f: Callable[[str], str], presheaf: Presheaf[T], target_topology: PosetTopology
) -> Presheaf[T]:
    """Pushforward (f_* F)(V) = F(f^{-1}(V))."""
    sections: Dict[OpenSet, List[T]] = {}
    for v_set in [
        target_topology.minimal_open_neighborhood(p) for p in target_topology.base_elements
    ]:
        preimage = frozenset(x for x in presheaf.topology.base_elements if f(x) in v_set.elements)
        u_preimage = OpenSet(preimage)
        sections[v_set] = presheaf.sections(u_preimage)

    return Presheaf(
        name=f"f_*({presheaf.name})",
        topology=target_topology,
        sections_map=sections,
        restriction_op=presheaf.restriction_op,
    )


# ==============================================================================
# 14. Inverse Image Sheaf (Pullback f^*) (SH-14)
# ==============================================================================


def pullback_presheaf(
    f: Callable[[str], str], source_topology: PosetTopology, target_sheaf: Presheaf[T]
) -> Presheaf[T]:
    """Pullback presheaf f^* G: assigns to U the colimit of G(V) for V superset f(U)."""
    sections: Dict[OpenSet, List[T]] = {}
    for p in source_topology.base_elements:
        u_p = source_topology.minimal_open_neighborhood(p)
        fp = f(p)
        v_fp = target_sheaf.topology.minimal_open_neighborhood(fp)
        sections[u_p] = target_sheaf.sections(v_fp)

    return Presheaf(
        name=f"f^*({target_sheaf.name})",
        topology=source_topology,
        sections_map=sections,
        restriction_op=target_sheaf.restriction_op,
    )


