# 4. Presheaf Morphisms (SH-04)
# ==============================================================================


@dataclass
class PresheafMorphism(Generic[T, V]):
    """A natural transformation alpha: F -> G between presheaves."""

    source: Presheaf[T]
    target: Presheaf[V]
    # alpha_U: F(U) -> G(U)
    component_map: Callable[[OpenSet, T], V]

    def apply(self, u: OpenSet, s: T) -> V:
        return self.component_map(u, s)

    def check_naturality(self, u: OpenSet, v: OpenSet, s: T) -> bool:
        """Verify: rho^U_V(alpha_U(s)) == alpha_V(rho^U_V(s))."""
        if not v.is_subset(u):
            return False
        left = self.target.restrict(u, v, self.apply(u, s))
        right = self.apply(v, self.source.restrict(u, v, s))
        return left == right


# ==============================================================================
# 5. Presheaf Kernel & Cokernel (SH-05)
# ==============================================================================


def presheaf_kernel(
    morph: PresheafMorphism[Tuple[Fraction, ...], Tuple[Fraction, ...]],
    zero_val: Tuple[Fraction, ...],
) -> Presheaf[Tuple[Fraction, ...]]:
    """Construct presheaf kernel: ker(alpha)(U) = {s in F(U) | alpha_U(s) == 0}."""
    ker_sections: Dict[OpenSet, List[Tuple[Fraction, ...]]] = {}
    for u, secs in morph.source.sections_map.items():
        ker_secs = [s for s in secs if morph.apply(u, s) == zero_val]
        ker_sections[u] = ker_secs

    return Presheaf(
        name=f"ker({morph.source.name})",
        topology=morph.source.topology,
        sections_map=ker_sections,
        restriction_op=morph.source.restriction_op,
    )


