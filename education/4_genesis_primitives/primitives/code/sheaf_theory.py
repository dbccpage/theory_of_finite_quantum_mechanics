# 24. Leray Acyclic Cover Theorem (SH-24)
# ==============================================================================


def check_leray_acyclic_condition(
    cover: List[OpenSet], h1_checker: Callable[[OpenSet], bool]
) -> bool:
    """Leray condition: H^q(U_{i_0 ... i_p}, F) = 0 for all intersections and q > 0."""
    for i in range(len(cover)):
        if not h1_checker(cover[i]):
            return False
        for j in range(i + 1, len(cover)):
            u_ij = cover[i].intersection(cover[j])
            if not u_ij.is_empty and not h1_checker(u_ij):
                return False
    return True


# ==============================================================================
# 25. Spectral Sequence of a Composition (SH-25)
# ==============================================================================


@dataclass
class LocalToGlobalSpectralSequencePage:
    """Page E_2^{p,q} of the local-to-global spectral sequence:
    E_2^{p,q} = H^p(U, H^q(F)) => H^{p+q}(X, F).
    """

    e2_table: Dict[Tuple[int, int], int]  # (p, q) -> dimension

    def total_cohomology_bound(self, degree: int) -> int:
        """Sum_{p+q = degree} dim E_2^{p,q}."""
        tot = 0
        for (p, q), d in self.e2_table.items():
            if p + q == degree:
                tot += d
        return tot
