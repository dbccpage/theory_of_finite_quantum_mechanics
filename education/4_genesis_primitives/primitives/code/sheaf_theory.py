# 6. Separated Presheaf (Locality S1) (SH-06)
# ==============================================================================


def check_separated(
    presheaf: Presheaf[T], u: OpenSet, cover: List[OpenSet]
) -> Tuple[bool, Optional[Tuple[T, T]]]:
    """Verify S1: if s, t in F(U) satisfy rho(s) == rho(t) on all U_i in cover, then s == t."""
    secs = presheaf.sections(u)
    for i, s1 in enumerate(secs):
        for s2 in secs[i + 1 :]:
            agree_on_all = True
            for u_i in cover:
                if presheaf.restrict(u, u_i, s1) != presheaf.restrict(u, u_i, s2):
                    agree_on_all = False
                    break
            if agree_on_all and s1 != s2:
                return False, (s1, s2)  # Violates S1
    return True, None


# ==============================================================================
# 7. Gluing Axiom (S2) & Sheaf Condition (SH-07)
# ==============================================================================


@dataclass
class SheafConditionResult(Generic[T]):
    is_sheaf: bool
    is_separated: bool
    unmatched_family: Optional[List[Tuple[OpenSet, T]]] = None
    witness_global_section: Optional[T] = None


def check_sheaf_condition(
    presheaf: Presheaf[T], u: OpenSet, cover: List[OpenSet]
) -> SheafConditionResult[T]:
    """Verify both S1 (separation) and S2 (gluing)."""
    sep_ok, sep_viol = check_separated(presheaf, u, cover)
    if not sep_ok:
        return SheafConditionResult(is_sheaf=False, is_separated=False)

    # Generate all candidate matching families {s_i in F(U_i)}
    cover_secs = [presheaf.sections(u_i) for u_i in cover]
    if any(len(s) == 0 for s in cover_secs):
        return SheafConditionResult(is_sheaf=True, is_separated=True)

    import itertools

    for family in itertools.product(*cover_secs):
        # Check pairwise compatibility on U_i cap U_j
        pairwise_compat = True
        for i in range(len(cover)):
            for j in range(i + 1, len(cover)):
                u_ij = cover[i].intersection(cover[j])
                if u_ij.is_empty:
                    continue
                res_i = presheaf.restrict(cover[i], u_ij, family[i])
                res_j = presheaf.restrict(cover[j], u_ij, family[j])
                if res_i != res_j:
                    pairwise_compat = False
                    break
            if not pairwise_compat:
                break

        if pairwise_compat:
            # Check if there exists a global section s in F(U) gluing this family
            gluing_found = False
            for s in presheaf.sections(u):
                if all(presheaf.restrict(u, cover[i], s) == family[i] for i in range(len(cover))):
                    gluing_found = True
                    break
            if not gluing_found:
                unmatched = [(cover[i], family[i]) for i in range(len(cover))]
                return SheafConditionResult(
                    is_sheaf=False, is_separated=True, unmatched_family=unmatched
                )

    return SheafConditionResult(is_sheaf=True, is_separated=True)


