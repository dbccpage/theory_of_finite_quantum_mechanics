# -*- coding: utf-8 -*-
"""
Triad Domain Contracts: Proposal, Evaluation, and Authority Separation.

Establishes the clean separation between:
1. Proposal (P): Generated by external proposer/engine (e.g. Alpha Engine).
2. Evaluation (E): Epistemic verification by CODA mathematical referee.
3. Authority (T): Normative authorization firewall enforcing coproduct separation.

Grounded in F004 Foundational Papers:
- Paper 004: Role Non-Impersonation (P, E, A are disjoint morphism classes)
- Paper 005: The Authority Gap (Verification != Authorization)
- Paper 027: The Authority Firewall (Coproduct T_auth + T_res + F_term)
- Paper 028: Finite Authority & Non-Terminal Computation (Budget bounds)
- Paper 029: The Anomalon Boundary (Real_0 = Diff union Struct)
- Paper 030: Authority Firewall and Verification Limits (Fail-closed limits)

AuthorityEffect: None.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, Mapping, Optional, Tuple

from coda_application.domain._seal import digest, seal_ok
from coda_application.domain.entities import (
    AuthorityToken,
    LayerExecutionRecord,
    MasterNormalFormOutcome,
    ProblemInstance,
    TerminalKind,
    freeze,
)
from coda_application.domain.value_objects import DualWitness, ExactRational

ALL_HALT_GUARDS = (
    "GUARD_1_ROLE_SEPARATION",
    "GUARD_2_EXACT_ARITHMETIC",
    "GUARD_3_DUAL_WITNESS_VALIDATION",
    "GUARD_4_COCYCLE_CONSISTENCY",
    "GUARD_5_AUTHORITY_GAP",
    "GUARD_6_NON_TERMINAL_BUDGET",
    "GUARD_7_VERIFICATION_LIMITS",
)
# GUARD_3 checks a dual witness; with Phi_1 = 0 and no witness there is nothing to check,
# and the firewall records that instead of reporting the guard as passed.
GUARD_3_NOT_APPLICABLE = "GUARD_3_NOT_APPLICABLE"


@dataclass(frozen=True)
class ProposalContract:
    """
    Proposal Contract (P).
    Submitted by an external dynamic actor (e.g. Alpha Engine).
    Encapsulates candidate solution, problem instance, and declared hypotheses.

    ROLE SEPARATION (Paper 004):
    Contains NO grant fields and NO authority flags. Proposers cannot self-grant authority.
    """

    proposer_id: str
    problem: ProblemInstance
    candidate_hypotheses: Tuple[str, ...] = ()
    candidate_metadata: Mapping[str, Any] = field(default_factory=dict)
    budget_limit_seconds: Optional[ExactRational] = None

    def __post_init__(self):
        if not isinstance(self.proposer_id, str) or not self.proposer_id.strip():
            raise ValueError("ProposalContract requires a non-empty proposer_id")
        if not isinstance(self.problem, ProblemInstance):
            raise TypeError("ProposalContract.problem must be a ProblemInstance")
        # Role Non-Impersonation (Paper 004): a proposer must not embed an authority
        # license inside its own proposal. Authorization is admitted only externally,
        # via a verified AuthorityGrant. Fail closed rather than silently accept a
        # self-granted license.
        if getattr(self.problem, "fda_license_granted", False):
            raise ValueError(
                "ROLE IMPERSONATION: ProposalContract.problem must not set "
                "fda_license_granted; authority is granted only via an external grant."
            )
        if self.budget_limit_seconds is not None:
            if not isinstance(self.budget_limit_seconds, ExactRational) or not self.budget_limit_seconds.is_positive:
                raise ValueError("budget_limit_seconds must be a positive ExactRational")
        object.__setattr__(self, "candidate_hypotheses", tuple(self.candidate_hypotheses))
        object.__setattr__(self, "candidate_metadata", freeze(dict(self.candidate_metadata)))


def _pair(r: Optional[ExactRational]):
    return None if r is None else [r.numerator, r.denominator]


def evidence_body(ev: "EvaluationContract") -> Dict[str, Any]:
    """Canonical body of an evaluation: what the evidence digest and the evaluator seal cover."""
    return {
        "problem_id": ev.problem_id,
        "problem_digest": ev.problem_digest,
        "phi1": _pair(ev.phi1),
        "gamma2": _pair(ev.gamma2),
        "witness": None if ev.dual_witness is None else [list(e) for e in ev.dual_witness.witness_vector],
        "repair": None if ev.primal_repair is None else [_pair(r) for r in ev.primal_repair],
        "valid": ev.is_mathematically_valid,
        "records": [[r.layer_id.value, r.succeeded] for r in ev.layer_records],
        "budget_satisfied": ev.budget_satisfied,
        "refusal": ev.refusal_reason,
    }


@dataclass(frozen=True)
class EvaluationContract:
    """
    Evaluation Contract (E).
    Emitted by CODA's epistemic verification stack.
    Carries mathematical evidence: exact quotient defect, cocycle violation, dual witness,
    primal repair, and layer traces.

    AUTHORITY GAP (Paper 005):
    Pure epistemic evidence. Zero authority. Mathematical validity (phi1 == 0 and gamma2 == 0)
    does NOT imply authorization.

    ``phi1``/``gamma2`` are None when the evaluation stopped before computing them
    (budget exhaustion, intake refusal): unknown evidence is never reported as a value.
    Evidence computed by the stack carries ``seal``; the firewall recomputes anything
    that does not.
    """

    problem_id: str
    phi1: Optional[ExactRational]
    gamma2: Optional[ExactRational]
    dual_witness: Optional[DualWitness]
    is_mathematically_valid: bool
    layer_records: Tuple[LayerExecutionRecord, ...]
    elapsed_seconds: ExactRational
    budget_satisfied: bool
    primal_repair: Optional[Tuple[ExactRational, ...]] = None
    problem_digest: str = ""
    evidence_digest: str = ""
    refusal_reason: Optional[str] = None
    seal: str = ""

    def __post_init__(self):
        object.__setattr__(self, "layer_records", tuple(self.layer_records))
        if self.primal_repair is not None:
            object.__setattr__(self, "primal_repair", tuple(self.primal_repair))

    @property
    def has_residual(self) -> bool:
        """True if a non-zero quotient or cocycle defect survives (unknown counts as present)."""
        if self.phi1 is None or self.gamma2 is None:
            return True
        return not self.phi1.is_zero or not self.gamma2.is_zero

    @property
    def is_sealed(self) -> bool:
        """Authenticate the decision fields listed in ``evidence_body``.

        Diagnostic messages, record metadata, record defect masses and elapsed
        time are not sealed. This property does not authenticate those fields.
        """
        body = evidence_body(self)
        return bool(self.evidence_digest) and digest(body) == self.evidence_digest and seal_ok(
            "evaluation", body, self.seal
        )


@dataclass(frozen=True)
class AuthorityContract:
    """
    Authority Contract (T).
    Emitted by the Authority Firewall.
    Implements the coproduct: T = T_auth + T_res + F_term (Paper 027).

    Guarantees under declared assumptions that authority tokens require an authenticated
    external license and that surviving residuals are retained as typed anomalons.
    Construction checks that the contract agrees with its outcome and that an AUTHORIZED
    contract records every halt guard as passed.
    """

    terminal_kind: TerminalKind
    authority_token: Optional[AuthorityToken]
    anomalon_fingerprint: Optional[str]
    halt_guards_passed: Tuple[str, ...]
    decision_reason: str
    outcome: MasterNormalFormOutcome

    def __post_init__(self):
        object.__setattr__(self, "halt_guards_passed", tuple(self.halt_guards_passed))
        if not isinstance(self.outcome, MasterNormalFormOutcome):
            raise TypeError("AuthorityContract.outcome must be a MasterNormalFormOutcome")
        if self.terminal_kind != self.outcome.terminal_kind:
            raise ValueError("AuthorityContract terminal differs from its outcome")
        if self.authority_token is not self.outcome.authority_token:
            raise ValueError("AuthorityContract token differs from its outcome's token")
        if self.terminal_kind == TerminalKind.AUTHORIZED:
            missing = [
                g
                for g in ALL_HALT_GUARDS
                if g not in self.halt_guards_passed
                and not (g == "GUARD_3_DUAL_WITNESS_VALIDATION" and GUARD_3_NOT_APPLICABLE in self.halt_guards_passed)
            ]
            if missing or not self.outcome.is_authorized:
                raise ValueError(f"AUTHORIZED contract without every halt guard passed: missing {missing}")

    @property
    def is_authorized(self) -> bool:
        return self.terminal_kind == TerminalKind.AUTHORIZED and self.outcome.is_authorized

    @property
    def is_closed_residual(self) -> bool:
        return self.terminal_kind == TerminalKind.CLOSED_RESIDUAL

    @property
    def is_refused(self) -> bool:
        return self.terminal_kind == TerminalKind.REFUSED
