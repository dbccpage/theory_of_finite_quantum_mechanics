"""Theorem-level Lean axiom census for the Algorithm Prime Triad package.

``python scripts/lean_census.py`` regenerates ``lean4/AxiomCensus.lean`` from the
``theorem`` declarations under ``lean4/Prime/``, builds the package, prints the
axioms of every theorem and writes ``lean4/axiom_report.txt``. It fails on a
``sorry``, ``admit`` or ``native_decide`` token, on a build failure, and on any
axiom outside ``AXIOM_WHITELIST``. ``--check`` compares instead of writing.

AuthorityEffect: None.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
LEAN_DIR = PACKAGE / "lean4"
CENSUS = LEAN_DIR / "AxiomCensus.lean"
REPORT = LEAN_DIR / "axiom_report.txt"
AXIOM_WHITELIST = frozenset({"propext", "Quot.sound"})
FORBIDDEN = re.compile(r"\b(?:sorry|admit|native_decide)\b")
THEOREM = re.compile(r"^theorem\s+(\S+)", re.MULTILINE)


def lake() -> str:
    found = shutil.which("lake") or str(Path.home() / ".elan" / "bin" / "lake")
    return found


def sources() -> list[Path]:
    return sorted((LEAN_DIR / "Prime").glob("*.lean")) + [LEAN_DIR / "Prime.lean"]


def theorem_names() -> list[str]:
    names: list[str] = []
    for path in sorted((LEAN_DIR / "Prime").glob("*.lean")):
        names.extend(f"Prime.{name}" for name in THEOREM.findall(path.read_text(encoding="utf-8")))
    return names


def render_census(names: list[str]) -> str:
    lines = ["-- Generated by scripts/lean_census.py. AuthorityEffect: None.", "import Prime", ""]
    lines.extend(f"#print axioms {name}" for name in names)
    return "\n".join(lines) + "\n"


def placeholder_problems() -> list[str]:
    problems = []
    for path in sources():
        if FORBIDDEN.search(path.read_text(encoding="utf-8")):
            problems.append(f"forbidden proof token in {path.relative_to(PACKAGE)}")
    return problems


def group_reports(transcript: str) -> list[str]:
    reports: list[str] = []
    lines = transcript.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if "does not depend on any axioms" in line:
            reports.append(line)
        elif "depends on axioms:" in line:
            chunk = [line]
            while "]" not in " ".join(chunk) and i + 1 < len(lines):
                i += 1
                chunk.append(lines[i].strip())
            reports.append(" ".join(chunk))
        i += 1
    return reports


def run_census(names: list[str]) -> tuple[str, list[str], list[str]]:
    """Build a clean copy and return (lean version, reports, problems)."""
    problems = placeholder_problems()
    if problems:
        return "", [], problems
    with tempfile.TemporaryDirectory(prefix="prime-lean-") as tmp:
        replay = Path(tmp) / "lean4"
        shutil.copytree(LEAN_DIR, replay, ignore=shutil.ignore_patterns(".lake", "b", "axiom_report.txt"))
        (replay / "AxiomCensus.lean").write_text(render_census(names), encoding="utf-8")
        version = subprocess.run([lake(), "env", "lean", "--version"], cwd=replay, capture_output=True, text=True)
        build = subprocess.run([lake(), "build"], cwd=replay, capture_output=True, text=True)
        if build.returncode:
            return "", [], ["lake build failed:\n" + build.stdout[-2000:] + build.stderr[-2000:]]
        census = subprocess.run(
            [lake(), "env", "lean", "AxiomCensus.lean"], cwd=replay, capture_output=True, text=True
        )
        if census.returncode:
            return "", [], ["axiom census failed:\n" + census.stdout[-2000:] + census.stderr[-2000:]]
    reports = group_reports(census.stdout + census.stderr)
    if len(reports) != len(names):
        problems.append(f"expected {len(names)} axiom reports, got {len(reports)}")
    for report in reports:
        match = re.search(r"depends on axioms:\s*\[([^]]*)]", report)
        if match:
            for axiom in (a.strip() for a in match.group(1).split(",")):
                if axiom not in AXIOM_WHITELIST:
                    problems.append(f"axiom outside whitelist: {axiom} in {report}")
    return " ".join(version.stdout.split()), reports, problems


def report_body(text: str) -> str:
    """Axiom report without the host toolchain banner."""
    kept = [line for line in text.splitlines() if not line.startswith("Toolchain:")]
    return "\n".join(kept) + "\n"


def lean_version_ok(version: str) -> bool:
    return version.startswith("Lean (version 4.34.0,")


def render_report(version: str, reports: list[str]) -> str:
    return (
        "Algorithm Prime Triad — theorem-level Lean axiom report\n"
        f"Toolchain: {version}\n"
        "Build command: lake build\n"
        "Census command: lake env lean AxiomCensus.lean\n"
        f"Theorem count: {len(reports)}\n"
        f"Allowed dependencies: {', '.join(sorted(AXIOM_WHITELIST))}\n\n"
        + "\n".join(reports)
        + "\n"
    )


def main(argv: list[str]) -> int:
    check = "--check" in argv
    names = theorem_names()
    census_text = render_census(names)
    version, reports, problems = run_census(names)
    if problems:
        for problem in problems:
            print(f"FAIL: {problem}", file=sys.stderr)
        return 1
    report_text = render_report(version, reports)
    if check:
        stale = []
        if not lean_version_ok(version):
            stale.append(f"Lean version {version!r} is not 4.34.0")
        if not CENSUS.is_file() or CENSUS.read_text(encoding="utf-8") != census_text:
            stale.append(str(CENSUS.relative_to(PACKAGE)))
        committed = REPORT.read_text(encoding="utf-8") if REPORT.is_file() else ""
        if report_body(committed) != report_body(report_text):
            stale.append(str(REPORT.relative_to(PACKAGE)))
        if stale:
            print("FAIL: stale " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"lean: {len(reports)} theorems, axioms within {sorted(AXIOM_WHITELIST)}; report current")
        return 0
    CENSUS.write_text(census_text, encoding="utf-8", newline="\n")
    REPORT.write_text(report_text, encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(PACKAGE)} with {len(reports)} theorem reports")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
