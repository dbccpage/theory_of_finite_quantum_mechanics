"""Build docs/claim_code_map.yaml, docs/claim_ir.yaml and docs/lean_claim_map.md
from the claim ledger, so the maps cannot drift from it.

``python scripts/build_claim_maps.py`` writes them; ``--check`` compares.
Engine counterparts are informational. AuthorityEffect: None.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
LEDGER = PACKAGE / "oe_prime_algorithms_claim_ledger.md"
CRATE = "omega_prime_runtime"
ROW = re.compile(r"^\| (OE\d{3}-\d{2}) \| ([^|]+) \| (.+) \| (.+) \|$", re.MULTILINE)
TEST = re.compile(r"(test_[a-z_]+\.py)::(test_[a-z0-9_]+)")
LEAN = re.compile(r"`(Prime\.[A-Za-z0-9_]+)`")

ENGINE = {
    "OE001-01": ["oeprmalg0::CandidatePacket", "oeprmalg0::IntakeTrace"],
    "OE001-02": ["oeprmalg0::admit_declaration", "oeprmalg0::AdmissionDecision"],
    "OE001-04": ["dda_alphabet::TraceTerminal::Terminalized"],
    "OE002-02": ["oeprmalg1::check_adapter", "oeprmalg1::AdapterLossLedger"],
    "OE002-03": ["oeprmalg1::AdapterStatus"],
    "OE003-01": ["oeprmalg2::can_continue_n", "oeprmalg2::CONTINUATION_CONJUNCTS"],
    "OE003-03": ["oeprmalg2::CanContinueInput::budget_remains"],
    "OE003-04": ["oeprmalg2::ProgressMetric"],
}


def claims() -> list[dict]:
    rows = []
    for claim_id, status, statement, evidence in ROW.findall(LEDGER.read_text(encoding="utf-8")):
        rows.append(
            {
                "id": claim_id,
                "status": status.strip(),
                "statement": statement.strip(),
                "tests": sorted({f"code/{f}::{t}" for f, t in TEST.findall(evidence)}),
                "lean": sorted(set(LEAN.findall(evidence))),
                "engine": ENGINE.get(claim_id, []),
            }
        )
    return rows


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_code_map(rows: list[dict]) -> str:
    out = [
        "# Generated by scripts/build_claim_maps.py from the claim ledger. AuthorityEffect: None.",
        "schema: algos.claim_code_map.v1",
        f"engine_crate: {CRATE}",
        "claims:",
    ]
    for row in rows:
        out.append(f"  - id: {row['id']}")
        out.append(f"    status: {_quote(row['status'])}")
        for key in ("tests", "lean", "engine"):
            if row[key]:
                out.append(f"    {key}:")
                out.extend(f"      - {_quote(item)}" for item in row[key])
            else:
                out.append(f"    {key}: []")
    return "\n".join(out) + "\n"


def render_ir(rows: list[dict]) -> str:
    out = [
        "# Generated by scripts/build_claim_maps.py from the claim ledger. AuthorityEffect: None.",
        "schema: algos.claim_ir.v1",
        "claims:",
    ]
    for row in rows:
        out.append(f"  - id: {row['id']}")
        out.append(f"    status: {_quote(row['status'])}")
        out.append(f"    statement: {_quote(row['statement'])}")
    return "\n".join(out) + "\n"


def render_lean_map(rows: list[dict]) -> str:
    out = [
        "# Lean claim map",
        "",
        "Generated by `scripts/build_claim_maps.py` from the claim ledger. Every",
        "declaration lives in `lean4/Prime/` and appears in `lean4/axiom_report.txt`.",
        "",
        "| Claim | Status | Lean declarations |",
        "|---|---|---|",
    ]
    for row in rows:
        if not row["lean"]:
            continue
        joined = ", ".join(f"`{item}`" for item in row["lean"])
        out.append(f"| {row['id']} | {row['status']} | {joined} |")
    return "\n".join(out) + "\n"


def render_yaml_ledger(rows: list[dict]) -> str:
    out = [
        "# Generated by scripts/build_claim_maps.py from the claim ledger. AuthorityEffect: None.",
        "paper_identity:",
        '  paper_id: "OE-000"',
        '  title: "Algorithm Prime Triad: Candidate Proposal, Declaration Order, Adapter Soundness, and Continuation Control"',
        '  canonical_version: "1.0.0"',
        '  paper_file: "oe_prime_algorithms.md"',
        '  authority_effect: "None"',
        "",
        "claims:",
    ]
    for row in rows:
        out.append(f"  - claim_id: {row['id']}")
        out.append(f"    status: {_quote(row['status'])}")
        out.append(f"    statement: {_quote(row['statement'])}")
        if row["tests"]:
            out.append("    tests:")
            out.extend(f"      - {_quote(item)}" for item in row["tests"])
        else:
            out.append("    tests: []")
        if row["lean"]:
            out.append("    lean:")
            out.extend(f"      - {_quote(item)}" for item in row["lean"])
        else:
            out.append("    lean: []")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    check_only = "--check" in args
    docs = PACKAGE / "docs"
    docs.mkdir(exist_ok=True)
    targets = {
        docs / "claim_code_map.yaml": render_code_map,
        docs / "claim_ir.yaml": render_ir,
        docs / "lean_claim_map.md": render_lean_map,
        PACKAGE / "oe_prime_algorithms_claim_ledger.yaml": render_yaml_ledger,
    }
    c = claims()
    mismatches: list[str] = []
    for path, render in targets.items():
        rendered = render(c)
        if check_only:
            if not path.is_file() or path.read_text(encoding="utf-8") != rendered:
                mismatches.append(str(path.relative_to(PACKAGE)))
        else:
            path.write_text(rendered, encoding="utf-8")
    if mismatches:
        for m in mismatches:
            print(f"STALE {m}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
