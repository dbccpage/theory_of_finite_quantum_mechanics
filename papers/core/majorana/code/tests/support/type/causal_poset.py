"""
CausalPoset — the discrete carrier P for self-repair dynamics.

Nodes define geometric events; edges define causal transport capabilities.
This is the base metric space on which the obstruction framework operates.
"""

from typing import Any, Dict, List, Tuple


class CausalPoset:
    """
    Exploration-layer directed geometric graph.

    Nodes carry 2D coordinates; edges encode allowed directed transport.
    The edges GENERATE a strict partial order BY REACHABILITY: a < b iff b is
    reachable from a along directed edges. Acyclicity (enforced via the DAG
    check) is what makes that reachability relation a strict partial order; the
    edge set itself is not required to be transitive or antisymmetric as given.
    Distance is Euclidean and is currently diagnostic only.
    """

    def __init__(self, node_coords: Dict, initial_edges: List[Tuple]):
        assert node_coords, "nodes must be non-empty"
        assert all(u in node_coords and v in node_coords for u, v in initial_edges), (
            "edges must reference known nodes"
        )
        assert all(
            isinstance(c, (tuple, list)) and len(c) == 2 for c in node_coords.values()
        ), "node coordinates must be 2D"

        self.nodes = node_coords  # {id: (x, y)}
        self.edges = list(initial_edges)

        assert self.is_acyclic(), (
            "CausalPoset edges must form a Directed Acyclic Graph (DAG)"
        )

    def is_acyclic(self) -> bool:
        """Verify the graph is a DAG (enforcing poset strict partial order)."""
        visited = set()
        rec_stack = set()

        adj: Dict[Any, List[Any]] = {n: [] for n in self.nodes}
        for u, v in self.edges:
            adj[u].append(v)

        def is_cyclic(node):
            if node in rec_stack:
                return True
            if node in visited:
                return False
            visited.add(node)
            rec_stack.add(node)
            for neighbor in adj[node]:
                if is_cyclic(neighbor):
                    return True
            rec_stack.remove(node)
            return False

        return not any(is_cyclic(n) for n in self.nodes)

    def precedes(self, a, b) -> bool:
        """Return True iff b is reachable from a along directed edges.

        This is the strict-partial-order relation a < b generated by the edges
        under the reachability interpretation (excludes a == b).
        """
        if a == b:
            return False
        adj: Dict[Any, List[Any]] = {n: [] for n in self.nodes}
        for u, v in self.edges:
            adj[u].append(v)
        stack = list(adj.get(a, []))
        seen = set()
        while stack:
            node = stack.pop()
            if node == b:
                return True
            if node in seen:
                continue
            seen.add(node)
            stack.extend(adj.get(node, []))
        return False

    def comparable(self, a, b) -> bool:
        """Return True iff a and b are order-comparable by reachability."""
        return self.precedes(a, b) or self.precedes(b, a)
