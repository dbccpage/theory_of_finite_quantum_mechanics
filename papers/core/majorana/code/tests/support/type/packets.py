"""PacketFamily structures and the canonical verification lifecycle.

Every realization packet runs through the lifecycle:
parse -> local_replay -> boundary_check -> terminalize.
"""

from typing import Any, Callable
from .refusal import Result, Refusal


class Seed:
    """The raw input data used to construct a packet."""

    def __init__(self, data: Any) -> None:
        self.data = data

    def __repr__(self) -> str:
        return f"Seed({self.data!r})"


class Packet:
    """The parsed, structured operational carrier."""

    def __init__(self, payload: Any) -> None:
        self.payload = payload

    def __repr__(self) -> str:
        return f"Packet({self.payload!r})"


class LocalEvidence:
    """Evidence generated by local/internal execution of the packet."""

    def __init__(self, metrics: Any) -> None:
        self.metrics = metrics

    def __repr__(self) -> str:
        return f"LocalEvidence({self.metrics!r})"


class BoundaryEvidence:
    """Evidence verifying that the local execution satisfies boundary constraints."""

    def __init__(self, signature: Any) -> None:
        self.signature = signature

    def __repr__(self) -> str:
        return f"BoundaryEvidence({self.signature!r})"


class PacketFamily:
    """Orchestrates parsing, local replay, boundary verification, and terminalization."""

    def __init__(
        self,
        name: str,
        parse_func: Callable[[Seed], Result[Packet]],
        local_replay_func: Callable[[Packet], Result[LocalEvidence]],
        boundary_check_func: Callable[
            [Packet, LocalEvidence], Result[BoundaryEvidence]
        ],
        terminalize_func: Callable[[Packet, BoundaryEvidence], Any],
    ) -> None:
        self.name = name
        self.parse_func = parse_func
        self.local_replay_func = local_replay_func
        self.boundary_check_func = boundary_check_func
        self.terminalize_func = terminalize_func

    def verify_and_terminalize(self, seed: Seed) -> Result[Any]:
        """Runs the canonical lifecycle pipeline."""
        packet_res = self.parse_func(seed)
        if isinstance(packet_res, Refusal):
            return packet_res

        evidence_res = self.local_replay_func(packet_res)
        if isinstance(evidence_res, Refusal):
            return evidence_res

        boundary_res = self.boundary_check_func(packet_res, evidence_res)
        if isinstance(boundary_res, Refusal):
            return boundary_res

        return self.terminalize_func(packet_res, boundary_res)


class DescentPacket:
    """Canonical 5-field dependent record (K, E, V, tau, Lambda) (spine §1.1/1.2)."""

    def __init__(
        self,
        K: Any,
        E: Any,
        V: Callable[[Any], Any],
        tau: Callable[[Any], Any],
        Lambda: Any,
    ) -> None:
        self.K = K
        self.E = E
        self.V = V
        self.tau = tau
        self.Lambda = Lambda

    def verify(self, packet_instance: Any) -> Any:
        """Applies the verification functor V, gates on licensing Lambda, and maps via tau."""
        if callable(self.Lambda):
            if not self.Lambda(packet_instance):
                return Refusal("UnlicensedTransport")

        evidence = self.V(packet_instance)
        if isinstance(evidence, Refusal):
            return evidence

        return self.tau(evidence)

    def __repr__(self) -> str:
        return f"DescentPacket(K={self.K!r}, E={self.E!r}, V={self.V!r}, tau={self.tau!r}, Lambda={self.Lambda!r})"
