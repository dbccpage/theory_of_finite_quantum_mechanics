def evaluate_clock_tower_control(conductor: int = 24) -> dict[str, Any]:
    """Run the QM-211 control exactly and return JSON-serializable results."""
    if conductor % 24 != 0:
        raise ClockControlRefusal("the control needs 24 | conductor")
    fourier = hbc.fourier_matrix_d4(conductor)
    shift = hbc.weyl_shift(4, conductor)
    clock3 = hbc.weyl_clock(3, conductor)
    return {
        "conductor": conductor,
        "spectral": {
            "fourier_d4": finite_spectral_theorem(fourier),
            "shift_d4": finite_spectral_theorem(shift),
            "clock_d3": finite_spectral_theorem(clock3),
        },
        "square_roots": {
            "fourier_d4": clock_square_roots(fourier),
            "shift_d4": clock_square_roots(shift),
            "clock_d3": clock_square_roots(clock3),
        },
        "tower": tower_chain_condition(conductor),
        "existing_refinement_tower": hbc.clock_refinement_tower(3, 3, conductor),
        "stochastic_control": stochastic_negative_control(conductor),
        "residual_import_ledger": residual_import_ledger(),
    }
