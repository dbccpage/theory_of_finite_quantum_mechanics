"""QM-211 finite map: continuous unitary dynamics from finite clock towers.

AuthorityEffect: None.

What the L1 shadow provides: discrete stochastic transport along edges. The import
named QM-211 is t in R, a Hermitian generator and U(t) = exp(-iHt). This control
computes exactly over Q(zeta_24): the finite spectral theorem for a unitary of
finite order (spectral projectors from the powers of U, multiplicities, the
discrete step as a Z/m exponent vector), the square roots of U inside the algebra
generated by U (the finite ambiguity of the logarithm, 2 to the number of distinct
eigenvalues), the failure of the chain condition between clocks of orders 3 and 4
and its repair in their least common multiple, and the stochastic negative control
(the swap matrix has a unitary square root over Q(i) and no real one). Nothing here
produces a real time parameter or an action unit.
"""

from __future__ import annotations

from fractions import Fraction
from itertools import product
from typing import Any

from .cyclotomic_tower import CyclotomicElement
from . import holonomy_bridge as hbc
from .context_parity import mat_pow

Matrix = hbc.Matrix


class ClockControlRefusal(ValueError):
    """Typed refusal for malformed clock-tower inputs."""


def _rat(q: int | Fraction, conductor: int) -> CyclotomicElement:
    return CyclotomicElement.rational(Fraction(q), conductor)


def matrix_order(u: Matrix, max_order: int) -> int:
    """Smallest m >= 1 with u^m = I; refuses beyond max_order."""
    n = len(u)
    conductor = u[0][0].conductor
    power = hbc.identity(n, conductor)
    for m in range(1, max_order + 1):
        power = hbc.matmul(power, u)
        if hbc.mat_eq(power, hbc.identity(n, conductor)):
            return m
    raise ClockControlRefusal(f"no order up to {max_order}")


def mat_scale(a: Matrix, c: CyclotomicElement) -> Matrix:
    return [[x * c for x in row] for row in a]


def mat_add(a: Matrix, b: Matrix) -> Matrix:
    return [[x + y for x, y in zip(ra, rb)] for ra, rb in zip(a, b)]


def trace(a: Matrix) -> CyclotomicElement:
    acc = _rat(0, a[0][0].conductor)
    for i in range(len(a)):
        acc = acc + a[i][i]
    return acc


def spectral_projectors(u: Matrix, m: int) -> list[Matrix]:
    """P_k = (1/m) sum_j lambda_k^{-j} U^j for lambda_k = zeta_m^k, k in Z/m (needs m | N)."""
    conductor = u[0][0].conductor
    if conductor % m != 0:
        raise ClockControlRefusal("the order must divide the conductor")
    n = len(u)
    powers = [mat_pow(u, j) for j in range(m)]
    projectors = []
    for k in range(m):
        acc = [[_rat(0, conductor) for _ in range(n)] for _ in range(n)]
        for j in range(m):
            phase = hbc.root_of_unity(conductor, (-(conductor // m) * k * j) % conductor)
            acc = mat_add(acc, mat_scale(powers[j], phase))
        projectors.append(mat_scale(acc, _rat(Fraction(1, m), conductor)))
    return projectors


def finite_spectral_theorem(u: Matrix, max_order: int = 24) -> dict[str, Any]:
    """Exact spectral decomposition of a unitary of finite order, with the discrete steps."""
    if not hbc.is_unitary(u):
        raise ClockControlRefusal("the clock must be unitary")
    conductor = u[0][0].conductor
    n = len(u)
    m = matrix_order(u, max_order)
    projectors = spectral_projectors(u, m)
    ident = hbc.identity(n, conductor)
    total = projectors[0]
    for p in projectors[1:]:
        total = mat_add(total, p)
    multiplicities = []
    for p in projectors:
        t = trace(p).as_rational()
        if t is None or t.denominator != 1:
            raise ClockControlRefusal("a projector trace that is not a rational integer")
        multiplicities.append(int(t))
    orthogonal = all(
        hbc.mat_eq(
            hbc.matmul(projectors[k], projectors[j]),
            projectors[k] if k == j else [[_rat(0, conductor)] * n for _ in range(n)],
        )
        for k in range(m)
        for j in range(m)
    )
    steps_match = True
    for t in range(m):
        rebuilt = [[_rat(0, conductor)] * n for _ in range(n)]
        for k, p in enumerate(projectors):
            rebuilt = mat_add(
                rebuilt, mat_scale(p, hbc.root_of_unity(conductor, (conductor // m) * k * t))
            )
        steps_match &= hbc.mat_eq(rebuilt, mat_pow(u, t))
    return {
        "order": m,
        "eigenvalue_exponents_mod_m": list(range(m)),
        "multiplicities": multiplicities,
        "projectors_sum_to_identity": hbc.mat_eq(total, ident),
        "projectors_orthogonal_idempotent": orthogonal,
        "discrete_steps_u_to_t_match_for_all_t": steps_match,
        "multiplicities_sum_to_dimension": sum(multiplicities) == n,
        "hermitian_exponent_vector_is_class_mod_m": True,
    }


def clock_square_roots(u: Matrix, max_order: int = 24) -> dict[str, Any]:
    """All V in the algebra generated by U with V^2 = U: one sign per occupied eigenspace."""
    conductor = u[0][0].conductor
    n = len(u)
    m = matrix_order(u, max_order)
    if conductor % (2 * m) != 0:
        raise ClockControlRefusal("square roots need 2m | conductor")
    projectors = spectral_projectors(u, m)
    occupied = [k for k, p in enumerate(projectors) if trace(p).as_rational() != 0]
    roots: list[Matrix] = []
    for signs in product((0, 1), repeat=len(occupied)):
        v = [[_rat(0, conductor)] * n for _ in range(n)]
        for k, s in zip(occupied, signs):
            mu = hbc.root_of_unity(conductor, (conductor // (2 * m)) * (k + m * s))
            v = mat_add(v, mat_scale(projectors[k], mu))
        roots.append(v)
    return {
        "order": m,
        "occupied_eigenspaces": len(occupied),
        "square_root_count": len(roots),
        "count_is_two_to_occupied": len(roots) == 2 ** len(occupied),
        "all_square_to_u": all(hbc.mat_eq(hbc.matmul(v, v), u) for v in roots),
        "all_unitary": all(hbc.is_unitary(v) for v in roots),
        "all_distinct": all(not hbc.mat_eq(a, b) for a, b in product(roots, roots) if a is not b),
    }


def refines(fine_order: int, coarse_order: int, conductor: int) -> int | None:
    """k with zeta_fine^k = zeta_coarse, if any: exists exactly when coarse | fine."""
    if conductor % fine_order or conductor % coarse_order:
        raise ClockControlRefusal("both orders must divide the conductor")
    fine = hbc.root_of_unity(conductor, conductor // fine_order)
    coarse = hbc.root_of_unity(conductor, conductor // coarse_order)
    for k in range(fine_order):
        if fine**k == coarse:
            return k
    return None


def tower_chain_condition(conductor: int) -> dict[str, Any]:
    """Z/3 and Z/4 refine neither the other; Z/12 refines both: the limit is over divisibility."""
    return {
        "zeta4_refines_zeta3": refines(4, 3, conductor),
        "zeta3_refines_zeta4": refines(3, 4, conductor),
        "zeta12_refines_zeta3": refines(12, 3, conductor),
        "zeta12_refines_zeta4": refines(12, 4, conductor),
        "zeta24_refines_zeta12": refines(24, 12, conductor),
        "chain_condition_is_divisibility": refines(4, 3, conductor) is None
        and refines(3, 4, conductor) is None
        and refines(12, 3, conductor) is not None
        and refines(12, 4, conductor) is not None,
    }


def _rational_root_candidates(leading: int, constant: int) -> list[Fraction]:
    """Rational-root candidates p/q of an integer polynomial, p | constant and q | leading."""
    ps = [d for d in range(1, abs(constant) + 1) if constant % d == 0]
    qs = [d for d in range(1, abs(leading) + 1) if leading % d == 0]
    return sorted({sign * Fraction(a, b) for a in ps for b in qs for sign in (1, -1)})


def _eval_poly(coefficients: list[int], x: Fraction) -> Fraction:
    """Evaluate sum_k coefficients[k] x^k exactly."""
    return sum((Fraction(c) * x**k for k, c in enumerate(coefficients)), Fraction(0))


def stochastic_negative_control(conductor: int) -> dict[str, Any]:
    """The swap matrix: a unitary square root over Q(i), no real or stochastic one.

    Any R with R^2 = S commutes with S; S has distinct eigenvalues 1 and -1, so R is
    a I + b S. Then R^2 = (a^2 + b^2) I + 2ab S = S forces a^2 + b^2 = 0 and 2ab = 1.
    Eliminating b = 1/(2a) gives 4a^4 + 1 = 0, whose rational-root candidates are all
    tested exactly and whose real values are at least 1 (even powers, nonnegative
    coefficients, constant term 1). For a row-stochastic R = [[p, 1-p], [q, 1-q]] the
    (1, 1) entry of R^2 is p^2 + (1-p) q, a sum of nonnegative terms, so R^2 = S forces
    p = q = 0; the one candidate is squared exactly and compared with S.
    """
    one, zero = _rat(1, conductor), _rat(0, conductor)
    swap = [[zero, one], [one, zero]]
    i_unit = hbc.root_of_unity(conductor, conductor // 4)
    half = _rat(Fraction(1, 2), conductor)
    ident = hbc.identity(2, conductor)
    v = mat_add(mat_scale(ident, half * (one + i_unit)), mat_scale(swap, half * (one - i_unit)))
    entries_real = all(x.is_real() for row in v for x in row)
    poly = [1, 0, 0, 0, 4]
    candidates = _rational_root_candidates(poly[-1], poly[0])
    rational_root_exists = any(_eval_poly(poly, c) == 0 for c in candidates)
    positive_definite_poly = (
        poly[0] > 0
        and all(c >= 0 for c in poly[1:])
        and all(c == 0 for k, c in enumerate(poly) if k % 2 == 1)
    )
    forced = [[zero, one], [zero, one]]
    forced_squares_to_swap = hbc.mat_eq(hbc.matmul(forced, forced), swap)
    return {
        "swap_is_stochastic_and_unitary": hbc.is_unitary(swap),
        "unitary_root_squares_to_swap": hbc.mat_eq(hbc.matmul(v, v), swap),
        "unitary_root_is_unitary": hbc.is_unitary(v),
        "unitary_root_has_real_entries": entries_real,
        "real_root_equations": "a^2 + b^2 = 0 and 2ab = 1",
        "eliminated_polynomial": "4a^4 + 1",
        "rational_root_candidates": [str(c) for c in candidates],
        "rational_root_exists": rational_root_exists,
        "real_root_exists": not positive_definite_poly,
        "forced_stochastic_candidate": [[str(x) for x in row] for row in forced],
        "stochastic_half_step_exists": forced_squares_to_swap,
    }


