def _mat2_q_mul(
    a: Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]],
    b: Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]],
) -> Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]]:
    return (
        (
            a[0][0] * b[0][0] + a[0][1] * b[1][0],
            a[0][0] * b[0][1] + a[0][1] * b[1][1],
        ),
        (
            a[1][0] * b[0][0] + a[1][1] * b[1][0],
            a[1][0] * b[0][1] + a[1][1] * b[1][1],
        ),
    )


def _mat2_q_add(
    a: Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]],
    b: Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]],
) -> Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]]:
    return (
        (a[0][0] + b[0][0], a[0][1] + b[0][1]),
        (a[1][0] + b[1][0], a[1][1] + b[1][1]),
    )


def _build_su2_doublet_dfm_audit() -> Su2DoubletDfmAudit:
    doublets = (
        (Vec2Qi(Qi.zero(), Qi.one()), Fraction(1, 1)),
        (Vec2Qi(Qi(Fraction(3, 5)), Qi(Fraction(4, 5))), Fraction(1, 1)),
        (
            Vec2Qi(Qi(Fraction(1, 3), Fraction(2, 3)), Qi(Fraction(2, 3))),
            Fraction(1, 1),
        ),
        (
            Vec2Qi(Qi(Fraction(2, 1), Fraction(4, 1)), Qi(Fraction(4, 1))),
            Fraction(6, 1),
        ),
    )
    su2_gauges = (
        Mat2Qi(
            Qi(Fraction(3, 5), Fraction(0, 1)),
            Qi(Fraction(0, 1), Fraction(4, 5)),
            Qi(Fraction(0, 1), Fraction(4, 5)),
            Qi(Fraction(3, 5), Fraction(0, 1)),
        ),
        Mat2Qi(
            Qi(Fraction(1, 3), Fraction(2, 3)),
            Qi(Fraction(2, 3), Fraction(0, 1)),
            Qi(Fraction(-2, 3), Fraction(0, 1)),
            Qi(Fraction(1, 3), Fraction(-2, 3)),
        ),
    )

    unitary_unimodular_ok = True
    goldstone_eliminated_ok = True
    su2_equivariance_ok = True
    dressed_doublet_inv_ok = True

    for phi, r_norm in doublets:
        u = su2_doublet_dressing_matrix(phi, r_norm)
        if (
            u.dagger().mul_mat(u) != Mat2Qi.identity()
            or u.mul_mat(u.dagger()) != Mat2Qi.identity()
            or u.det() != Qi.one()
        ):
            unitary_unimodular_ok = False
        expected_dressed = Vec2Qi(Qi.zero(), Qi(r_norm, Fraction(0, 1)))
        if u.dagger().mul_vec(phi) != expected_dressed:
            goldstone_eliminated_ok = False
        for g in su2_gauges:
            g_phi = g.mul_vec(phi)
            u_g_phi = su2_doublet_dressing_matrix(g_phi, r_norm)
            if u_g_phi != g.mul_mat(u):
                su2_equivariance_ok = False
            if u_g_phi.dagger().mul_vec(g_phi) != expected_dressed:
                dressed_doublet_inv_ok = False

    phi_x, r_x = doublets[2]
    phi_y, r_y = doublets[1]
    u_x = su2_doublet_dressing_matrix(phi_x, r_x)
    u_y = su2_doublet_dressing_matrix(phi_y, r_y)
    psi_l_x = Vec2Qi(
        Qi(Fraction(1, 2), Fraction(-1, 3)),
        Qi(Fraction(2, 5), Fraction(1, 7)),
    )
    link_xy = su2_gauges[0]
    psi_dressed_base = u_x.dagger().mul_vec(psi_l_x)
    link_dressed_base = u_x.dagger().mul_mat(link_xy).mul_mat(u_y)

    g_x = su2_gauges[0]
    g_y = su2_gauges[1]
    u_x_gauged = su2_doublet_dressing_matrix(g_x.mul_vec(phi_x), r_x)
    u_y_gauged = su2_doublet_dressing_matrix(g_y.mul_vec(phi_y), r_y)
    psi_dressed_gauged = u_x_gauged.dagger().mul_vec(g_x.mul_vec(psi_l_x))
    link_dressed_gauged = (
        u_x_gauged.dagger()
        .mul_mat(g_x.mul_mat(link_xy).mul_mat(g_y.dagger()))
        .mul_mat(u_y_gauged)
    )
    dressed_fermion_and_link_ok = (psi_dressed_gauged == psi_dressed_base) and (
        link_dressed_gauged == link_dressed_base
    )

    phase_half = Qi(Fraction(3, 5), Fraction(4, 5))
    diag_t3_phase = Mat2Qi(phase_half.conj(), Qi.zero(), Qi.zero(), phase_half)
    hypercharge_t3_ok = True
    for phi, r_norm in doublets:
        phi_phased = Vec2Qi(phase_half * phi.v0, phase_half * phi.v1)
        u_phased = su2_doublet_dressing_matrix(phi_phased, r_norm)
        u_base = su2_doublet_dressing_matrix(phi, r_norm)
        if u_phased != u_base.mul_mat(diag_t3_phase):
            hypercharge_t3_ok = False

    return Su2DoubletDfmAudit(
        doublet_witness_count=len(doublets),
        dressing_unitary_and_unimodular=unitary_unimodular_ok,
        goldstone_eliminated_without_gauge_fixing=goldstone_eliminated_ok,
        su2_left_equivariance_holds=su2_equivariance_ok,
        dressed_doublet_su2_invariant=dressed_doublet_inv_ok,
        dressed_fermion_and_link_su2_invariant=dressed_fermion_and_link_ok,
        hypercharge_phase_shifts_by_t3=hypercharge_t3_ok,
    )


def _build_weinberg_custodial_audit() -> WeinbergCustodialAudit:
    coupling_samples = (
        (Fraction(4, 5), Fraction(3, 5), Fraction(2, 1)),
        (Fraction(2, 3), Fraction(1, 2), Fraction(3, 1)),
        (Fraction(1, 1), Fraction(1, 1), Fraction(1, 1)),
        (Fraction(5, 7), Fraction(3, 7), Fraction(4, 1)),
    )
    id2 = ((Fraction(1, 1), Fraction(0, 1)), (Fraction(0, 1), Fraction(1, 1)))
    zero2 = ((Fraction(0, 1), Fraction(0, 1)), (Fraction(0, 1), Fraction(0, 1)))

    det_zero_ok = True
    trace_mz_ok = True
    projectors_ok = True
    sin2_cos2_ok = True
    e_sq_harmonic_ok = True
    custodial_all_ok = True
    rho_witness = Fraction(1, 1)
    rho_seen = False

    for g, gp, v in coupling_samples:
        g2 = g * g
        gp2 = gp * gp
        denom = g2 + gp2
        v2_quarter = (v * v) / Fraction(4, 1)
        m_w_sq = v2_quarter * g2
        m_z_sq = v2_quarter * denom

        m_neutral_sq = (
            (v2_quarter * g2, -v2_quarter * g * gp),
            (-v2_quarter * g * gp, v2_quarter * gp2),
        )
        det_val = (
            m_neutral_sq[0][0] * m_neutral_sq[1][1]
            - m_neutral_sq[0][1] * m_neutral_sq[1][0]
        )
        trace_val = m_neutral_sq[0][0] + m_neutral_sq[1][1]
        if det_val != Fraction(0, 1):
            det_zero_ok = False
        if trace_val != m_z_sq:
            trace_mz_ok = False

        sin2_w = gp2 / denom
        cos2_w = g2 / denom
        if sin2_w + cos2_w != Fraction(1, 1):
            sin2_cos2_ok = False
        e_sq = (g2 * gp2) / denom
        if (
            e_sq != g2 * sin2_w
            or e_sq != gp2 * cos2_w
            or (Fraction(1, 1) / e_sq) != (Fraction(1, 1) / g2 + Fraction(1, 1) / gp2)
        ):
            e_sq_harmonic_ok = False

        pi_gamma = (
            (gp2 / denom, (g * gp) / denom),
            ((g * gp) / denom, g2 / denom),
        )
        pi_z = (
            (g2 / denom, -(g * gp) / denom),
            (-(g * gp) / denom, gp2 / denom),
        )
        m_z_scaled_pi_z = (
            (m_z_sq * pi_z[0][0], m_z_sq * pi_z[0][1]),
            (m_z_sq * pi_z[1][0], m_z_sq * pi_z[1][1]),
        )
        if (
            _mat2_q_mul(pi_gamma, pi_gamma) != pi_gamma
            or _mat2_q_mul(pi_z, pi_z) != pi_z
            or _mat2_q_mul(pi_gamma, pi_z) != zero2
            or _mat2_q_mul(pi_z, pi_gamma) != zero2
            or _mat2_q_add(pi_gamma, pi_z) != id2
            or _mat2_q_mul(m_neutral_sq, pi_gamma) != zero2
            or _mat2_q_mul(m_neutral_sq, pi_z) != m_z_scaled_pi_z
        ):
            projectors_ok = False

        rho_ew = m_w_sq / (m_z_sq * cos2_w)
        if not rho_seen:
            rho_witness = rho_ew
            rho_seen = True
        if rho_ew != Fraction(1, 1):
            custodial_all_ok = False
            rho_witness = rho_ew

    gut_ratio = Fraction(3, 5)
    su5_sin2 = gut_ratio / (Fraction(1, 1) + gut_ratio)
    su5_cos2 = Fraction(1, 1) / (Fraction(1, 1) + gut_ratio)
    t_triplet = Fraction(1, 1)
    t3_triplet = Fraction(-1, 1)
    rho_triplet_y1 = (t_triplet * (t_triplet + 1) - t3_triplet * t3_triplet) / (
        2 * t3_triplet * t3_triplet
    )

    return WeinbergCustodialAudit(
        neutral_mass_matrix_det_zero_all_couplings=det_zero_ok,
        neutral_mass_matrix_trace_equals_mz_sq=trace_mz_ok,
        weinberg_projectors_idempotent_orthogonal_complete=projectors_ok,
        weinberg_sin2_plus_cos2_is_one=sin2_cos2_ok,
        electric_charge_e_sq_harmonic_identity=e_sq_harmonic_ok,
        pythagorean_4_5_3_5_sin2_theta_w=Fraction(9, 25),
        pythagorean_4_5_3_5_cos2_theta_w=Fraction(16, 25),
        su5_gut_sin2_theta_w=su5_sin2,
        su5_gut_cos2_theta_w=su5_cos2,
        custodial_rho_parameter_exact_one=rho_witness,
        custodial_rho_holds_all_couplings=custodial_all_ok,
        scalar_triplet_y1_rho_parameter=rho_triplet_y1,
    )


def _build_gell_mann_nishijima_audit() -> GellMannNishijimaAudit:
    y_q = Fraction(1, 6)
    y_u = Fraction(2, 3)
    y_d = Fraction(-1, 3)
    y_l = Fraction(-1, 2)
    y_e = Fraction(-1, 1)

    q_u_l = Fraction(1, 2) + y_q
    q_d_l = Fraction(-1, 2) + y_q
    q_u_r = y_u
    q_d_r = y_d
    q_nu_l = Fraction(1, 2) + y_l
    q_e_l = Fraction(-1, 2) + y_l
    q_e_r = y_e

    chirality_match = (
        (q_u_l == q_u_r)
        and (q_d_l == q_d_r)
        and (q_e_l == q_e_r)
        and (q_nu_l == Fraction(0, 1))
    )
    q_proton = 2 * q_u_l + q_d_l
    q_neutron = q_u_l + 2 * q_d_l
    charge_neutrality = (
        (q_proton == Fraction(1, 1))
        and (q_neutron == Fraction(0, 1))
        and (q_proton + q_e_l == Fraction(0, 1))
    )

    sin2_gut = Fraction(3, 8)
    cv_u = Fraction(1, 2) - 2 * q_u_l * sin2_gut
    cv_d = Fraction(-1, 2) - 2 * q_d_l * sin2_gut
    cv_nu = Fraction(1, 2) - 2 * q_nu_l * sin2_gut
    cv_e = Fraction(-1, 2) - 2 * q_e_l * sin2_gut

    return GellMannNishijimaAudit(
        gell_mann_nishijima_charges=(q_u_l, q_d_l, q_nu_l, q_e_l),
        vectorlike_em_current_chirality_match=chirality_match,
        proton_neutron_atom_charge_neutrality=charge_neutrality,
        z_boson_vector_couplings_at_sin2_3_8=(cv_u, cv_d, cv_nu, cv_e),
        z_boson_axial_couplings=(
            Fraction(1, 2),
            Fraction(-1, 2),
            Fraction(1, 2),
            Fraction(-1, 2),
        ),
    )


