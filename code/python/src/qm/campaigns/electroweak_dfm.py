@dataclass(frozen=True)
class Qi:
    """Exact Gaussian rational re + im * i with re, im in Q and i^2 = -1."""

    re: Fraction
    im: Fraction = Fraction(0, 1)

    @staticmethod
    def zero() -> "Qi":
        return Qi(Fraction(0, 1), Fraction(0, 1))

    @staticmethod
    def one() -> "Qi":
        return Qi(Fraction(1, 1), Fraction(0, 1))

    def conj(self) -> "Qi":
        return Qi(self.re, -self.im)

    def norm_sq(self) -> Fraction:
        return self.re * self.re + self.im * self.im

    def __add__(self, other: "Qi") -> "Qi":
        return Qi(self.re + other.re, self.im + other.im)

    def __sub__(self, other: "Qi") -> "Qi":
        return Qi(self.re - other.re, self.im - other.im)

    def __neg__(self) -> "Qi":
        return Qi(-self.re, -self.im)

    def __mul__(self, other: "Qi") -> "Qi":
        return Qi(
            self.re * other.re - self.im * other.im,
            self.re * other.im + self.im * other.re,
        )

    def scale(self, s: Fraction) -> "Qi":
        return Qi(self.re * s, self.im * s)


@dataclass(frozen=True)
class Vec2Qi:
    """Two-component SU(2)_L doublet over Q[i]."""

    v0: Qi
    v1: Qi

    def norm_sq(self) -> Fraction:
        return self.v0.norm_sq() + self.v1.norm_sq()


@dataclass(frozen=True)
class Mat2Qi:
    """2x2 matrix over Q[i]."""

    a00: Qi
    a01: Qi
    a10: Qi
    a11: Qi

    @staticmethod
    def identity() -> "Mat2Qi":
        return Mat2Qi(Qi.one(), Qi.zero(), Qi.zero(), Qi.one())

    def dagger(self) -> "Mat2Qi":
        return Mat2Qi(
            self.a00.conj(),
            self.a10.conj(),
            self.a01.conj(),
            self.a11.conj(),
        )

    def det(self) -> Qi:
        return (self.a00 * self.a11) - (self.a01 * self.a10)

    def mul_mat(self, other: "Mat2Qi") -> "Mat2Qi":
        return Mat2Qi(
            (self.a00 * other.a00) + (self.a01 * other.a10),
            (self.a00 * other.a01) + (self.a01 * other.a11),
            (self.a10 * other.a00) + (self.a11 * other.a10),
            (self.a10 * other.a01) + (self.a11 * other.a11),
        )

    def mul_vec(self, v: Vec2Qi) -> Vec2Qi:
        return Vec2Qi(
            (self.a00 * v.v0) + (self.a01 * v.v1),
            (self.a10 * v.v0) + (self.a11 * v.v1),
        )


def su2_doublet_dressing_matrix(phi: Vec2Qi, radial_norm_r: Fraction) -> Mat2Qi:
    """Construct u(Phi) = (1/r) * [[phi_0^*, phi_+], [-phi_+^*, phi_0]] in SU(2, Q[i])."""
    if radial_norm_r <= Fraction(0, 1):
        raise ValueError("radial_norm_r must be strictly positive")
    if phi.norm_sq() != radial_norm_r * radial_norm_r:
        raise ValueError("Doublet norm squared must equal radial_norm_r^2")
    inv_r = Fraction(1, 1) / radial_norm_r
    phi_plus = phi.v0
    phi_zero = phi.v1
    return Mat2Qi(
        phi_zero.conj().scale(inv_r),
        phi_plus.scale(inv_r),
        (-phi_plus.conj()).scale(inv_r),
        phi_zero.scale(inv_r),
    )




