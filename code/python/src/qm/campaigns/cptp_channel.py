r"""
Finite channels: Kraus form, the Choi matrix, and Wigner--Yanase monotonicity.

AuthorityEffect: None.

Canonical Implementation: finite_qm.use_cases.cptp_channel

A channel is :math:`\mathcal E(\rho) = \sum_k K_k\rho K_k^\dagger` with
:math:`\sum_k K_k^\dagger K_k = I`. Complete positivity is checked through the Choi matrix
:math:`J(\mathcal E) = (\mathcal E \otimes \mathrm{id})(|\Omega\rangle\langle\Omega|)`
rather than asserted.
"""

from __future__ import annotations

from typing import Any, Dict, List, Sequence

import numpy as np
import scipy.linalg

from ..domain.primitives import (
    SIGMA_Z,
    commutator,
    dagger,
)
from ..domain.primitives import (
    trace_norm as _kraus_trace_norm,
)


def is_trace_preserving(kraus_ops: Sequence[np.ndarray], atol: float = 1e-6) -> bool:
    r""":math:`\sum_k K_k^\dagger K_k = I`."""
    d = kraus_ops[0].shape[1]
    total = sum(dagger(k) @ k for k in kraus_ops)
    return bool(np.allclose(total, np.eye(d), atol=atol))


def apply_channel(rho: np.ndarray, kraus_ops: Sequence[np.ndarray]) -> np.ndarray:
    r""":math:`\mathcal E(\rho) = \sum_k K_k \rho K_k^\dagger`."""
    return sum(k @ rho @ dagger(k) for k in kraus_ops)


def choi_matrix(kraus_ops: Sequence[np.ndarray]) -> np.ndarray:
    r"""The Choi matrix of the channel, on :math:`H \otimes H`."""
    d = kraus_ops[0].shape[1]
    j = np.zeros((d * d, d * d), dtype=complex)
    for i in range(d):
        for k in range(d):
            eij = np.zeros((d, d), dtype=complex)
            eij[i, k] = 1.0
            j += np.kron(eij, apply_channel(eij, kraus_ops))
    return j


def is_completely_positive(kraus_ops: Sequence[np.ndarray], atol: float = 1e-9) -> bool:
    r"""CP iff the Choi matrix is positive semidefinite (Choi's theorem)."""
    evals = np.linalg.eigvalsh(choi_matrix(kraus_ops))
    return bool(np.all(evals >= -atol))


def wigner_yanase_skew_information(rho: np.ndarray, h_op: np.ndarray) -> float:
    r""":math:`I_\rho(H) = -\tfrac12\operatorname{Tr}([\sqrt\rho, H]^2)`."""
    evals, evecs = np.linalg.eigh(rho)
    nonneg_evals = np.where(evals > 0, evals, 0.0)
    sqrt_rho = evecs @ np.diag(np.sqrt(nonneg_evals)) @ dagger(evecs)
    comm = commutator(sqrt_rho, h_op)
    return float(-0.5 * np.real(np.trace(comm @ comm)))


def is_unital(kraus_ops: Sequence[np.ndarray], atol: float = 1e-9) -> bool:
    r""":math:`\mathcal E(I) = I`, i.e. :math:`\sum_k K_k K_k^\dagger = I`."""
    d = kraus_ops[0].shape[0]
    return bool(np.allclose(sum(k @ dagger(k) for k in kraus_ops), np.eye(d), atol=atol))


def is_covariant(
    kraus_ops: Sequence[np.ndarray],
    h_op: np.ndarray,
    times: Sequence[float] = (0.1, 0.6, 1.3, 2.0),
    n_probe: int = 12,
    atol: float = 1e-9,
) -> bool:
    r"""Is :math:`\mathcal E` covariant for the :math:`U(1)` group generated by :math:`H`?"""
    from scipy.linalg import expm

    d = np.asarray(h_op).shape[0]
    rng = np.random.default_rng(3)
    probes = []
    for _ in range(n_probe):
        m = rng.normal(size=(d, d)) + 1j * rng.normal(size=(d, d))
        m = m @ dagger(m)
        probes.append(m / np.real(np.trace(m)))

    for t in times:
        u = expm(-1j * np.asarray(h_op, dtype=complex) * t)
        for rho in probes:
            lhs = apply_channel(u @ rho @ dagger(u), kraus_ops)
            rhs = u @ apply_channel(rho, kraus_ops) @ dagger(u)
            if not np.allclose(lhs, rhs, atol=atol):
                return False
    return True


def hadamard_kraus() -> List[np.ndarray]:
    r"""The Hadamard channel."""
    return [np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2.0)]


def solve_covariant_wigner_yanase_monotonicity(
    rho: np.ndarray,
    kraus_ops: List[np.ndarray],
    h_op: np.ndarray,
) -> Dict[str, Any]:
    r"""QAM-001: Wigner-Yanase monotonicity under CPTP and covariance."""
    is_tp = is_trace_preserving(kraus_ops)
    is_cp = is_completely_positive(kraus_ops)
    covariant = is_covariant(kraus_ops, h_op)
    unital = is_unital(kraus_ops)
    hypotheses_hold = bool(is_tp and is_cp and covariant)

    i_rho_h = wigner_yanase_skew_information(rho, h_op)
    i_channel = wigner_yanase_skew_information(apply_channel(rho, kraus_ops), h_op)

    delta_i = i_rho_h - i_channel
    inequality_observed = bool(delta_i >= -1e-9)

    if not hypotheses_hold:
        status = "HYPOTHESES_NOT_MET"
    elif inequality_observed:
        status = "COVARIANT_WIGNER_YANASE_MONOTONICITY_VERIFIED"
    else:
        status = "MONOTONICITY_VIOLATED_UNDER_VERIFIED_HYPOTHESES"

    return {
        "is_trace_preserving": is_tp,
        "is_completely_positive": is_cp,
        "is_unital": unital,
        "is_covariant": covariant,
        "hypotheses_hold": hypotheses_hold,
        "i_rho_h": i_rho_h,
        "i_channel": i_channel,
        "delta_i": delta_i,
        "inequality_observed": inequality_observed,
        "status": status,
        "non_claims": [
            "NOT claimed for general CPTP maps (amplitude damping counterexample)",
            "NOT claimed for unital CPTP maps (Hadamard counterexample)",
            "covariance is sufficient, not necessary",
        ],
        "authority_effect": "None",
    }


def solve_unital_wigner_yanase_monotonicity(
    rho: np.ndarray, kraus_ops: List[np.ndarray], h_op: np.ndarray
) -> Dict[str, Any]:
    return solve_covariant_wigner_yanase_monotonicity(rho, kraus_ops, h_op)


def solve_cptp_wigner_yanase_monotonicity(
    rho: np.ndarray, kraus_ops: List[np.ndarray], h_op: np.ndarray
) -> Dict[str, Any]:
    return solve_covariant_wigner_yanase_monotonicity(rho, kraus_ops, h_op)


def trace_distance_contraction(
    rho: np.ndarray, sigma: np.ndarray, kraus_ops: Sequence[np.ndarray]
) -> Dict[str, Any]:
    before = _kraus_trace_norm(rho - sigma)
    after = _kraus_trace_norm(apply_channel(rho, kraus_ops) - apply_channel(sigma, kraus_ops))
    return {
        "trace_norm_before": before,
        "trace_norm_after": after,
        "contraction_factor": (after / before) if before > 1e-12 else 1.0,
        "is_contractive": bool(after <= before + 1e-9),
        "non_claim": "CPTP monotonicity alone does not select the trace norm (qm_080 Thm 2)",
        "authority_effect": "None",
    }


def dephasing_kraus(p: float) -> List[np.ndarray]:
    return [np.sqrt(1.0 - p) * np.eye(2, dtype=complex), np.sqrt(p) * SIGMA_Z]


def amplitude_damping_kraus(gamma: float) -> List[np.ndarray]:
    k0 = np.array([[1.0, 0.0], [0.0, np.sqrt(1.0 - gamma)]], dtype=complex)
    k1 = np.array([[0.0, np.sqrt(gamma)], [0.0, 0.0]], dtype=complex)
    return [k0, k1]


def trace_norm(A: np.ndarray) -> float:
    return float(np.real(np.sum(scipy.linalg.svdvals(A))))

def apply_depolarizing_channel(rho: np.ndarray, p: float) -> np.ndarray:
    d = rho.shape[0]
    return (1.0 - p) * rho + p * (np.eye(d) / d)

def verify_cptp_contractivity(rho1: np.ndarray, rho2: np.ndarray, p: float) -> bool:
    dist_before = trace_norm(rho1 - rho2)
    rho1_out = apply_depolarizing_channel(rho1, p)
    rho2_out = apply_depolarizing_channel(rho2, p)
    dist_after = trace_norm(rho1_out - rho2_out)
    return dist_after <= dist_before + 1e-12

def construct_dual_witness(diff: np.ndarray) -> np.ndarray:
    r"""Constructs the optimal dual witness operator W = U V^\dagger attaining trace norm."""
    U, s, Vt = scipy.linalg.svd(diff)
    return U @ Vt

def verify_dual_witness_bound(rho1: np.ndarray, rho2: np.ndarray) -> bool:
    diff = rho1 - rho2
    t_norm = trace_norm(diff)
    W_opt = construct_dual_witness(diff)
    alignment = float(np.real(np.trace(W_opt.conj().T @ diff)))
    # Duality gap zero: alignment == trace_norm
    return bool(np.isclose(alignment, t_norm, atol=1e-10))

