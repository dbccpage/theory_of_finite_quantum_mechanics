def derive_scale(Gm,perms):
    """The selection theorem replayed on a supplied symmetric Gram matrix and permutation set.

    ('scalar',c,I) when G == c*I with c = G_00 (sector additive, invariant under every supplied
    permutation, and the group they generate transitive); otherwise the first failing hypothesis with an
    exact witness: ('not_symmetric',(i,j)), ('not_sector_additive',...), ('not_invariant',(sigma,...)) or
    ('not_transitive',(i,j,orbits,orbit_values)) where orbit_values lists the (constant) diagonal value on
    each orbit, the statement that survives without transitivity."""
    Gm=matrix(Gm);n=len(Gm)
