//! Alexandrov poset topology, open sets, and covers (SH-01, Cover Contract).
//!
//! AuthorityEffect: None.

use omega_homology::simplicial::{OrientedSimplex, SimplicialComplex};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

/// An open set in the Alexandrov topology of a finite poset / simplicial complex.
///
/// For a simplicial complex K, open sets in the face poset are up-sets:
/// if simplex sigma in U and tau contains sigma, then tau in U (stars of subcomplexes).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct OpenSet {
    pub elements: BTreeSet<String>,
}

impl OpenSet {
    pub fn new(elements: impl IntoIterator<Item = impl Into<String>>) -> Self {
        Self {
            elements: elements.into_iter().map(Into::into).collect(),
        }
    }

    pub fn empty() -> Self {
        Self {
            elements: BTreeSet::new(),
        }
    }

    pub fn contains(&self, item: &str) -> bool {
        self.elements.contains(item)
    }

    pub fn is_subset(&self, other: &Self) -> bool {
        self.elements.is_subset(&other.elements)
    }

    pub fn union(&self, other: &Self) -> Self {
        Self {
            elements: self.elements.union(&other.elements).cloned().collect(),
        }
    }

    pub fn intersection(&self, other: &Self) -> Self {
        Self {
            elements: self
                .elements
                .intersection(&other.elements)
                .cloned()
                .collect(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.elements.is_empty()
    }

    pub fn len(&self) -> usize {
        self.elements.len()
    }
}

/// Alexandrov topology generated by a finite poset or simplicial complex.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PosetTopology {
    pub base_elements: BTreeSet<String>,
    /// Poset relation: (x, y) means x <= y (y is in the closure or star of x).
    pub le_relation: BTreeSet<(String, String)>,
}

impl PosetTopology {
    pub fn new(
        base_elements: impl IntoIterator<Item = impl Into<String>>,
        le_relation: impl IntoIterator<Item = (impl Into<String>, impl Into<String>)>,
    ) -> Self {
        Self {
            base_elements: base_elements.into_iter().map(Into::into).collect(),
            le_relation: le_relation
                .into_iter()
                .map(|(a, b)| (a.into(), b.into()))
                .collect(),
        }
    }

    /// Construct a discrete topology on base elements (only identity relations x <= x).
    pub fn discrete(base_elements: impl IntoIterator<Item = impl Into<String>>) -> Self {
        let elems: BTreeSet<String> = base_elements.into_iter().map(Into::into).collect();
        let rel: BTreeSet<(String, String)> =
            elems.iter().map(|x| (x.clone(), x.clone())).collect();
        Self {
            base_elements: elems,
            le_relation: rel,
        }
    }

    /// Construct the Alexandrov topology directly from an omega_homology SimplicialComplex.
    /// Elements are simplex vertex strings, and sigma <= tau means sigma is a face of tau (tau is in star(sigma)).
    pub fn from_simplicial_complex(complex: &SimplicialComplex) -> Self {
        let mut base_elements = BTreeSet::new();
        let mut le_relation = BTreeSet::new();
        let mut all_simplices = Vec::new();

        for dim in 0..=complex.max_dimension() {
            for s in complex.simplices(dim) {
                let id = format!("{:?}", s.vertices());
                base_elements.insert(id.clone());
                all_simplices.push((s.clone(), id));
            }
        }

        // Poset relation: sigma <= tau if vertices(sigma) is subset of vertices(tau)
        for (s1, id1) in &all_simplices {
            let v1: BTreeSet<usize> = s1.vertices().iter().copied().collect();
            for (s2, id2) in &all_simplices {
                let v2: BTreeSet<usize> = s2.vertices().iter().copied().collect();
                if v1.is_subset(&v2) {
                    le_relation.insert((id1.clone(), id2.clone()));
                }
            }
        }

        Self {
            base_elements,
            le_relation,
        }
    }

    /// The minimal open set containing x: U_x = {y | x <= y} (the star).
    pub fn minimal_open_neighborhood(&self, x: &str) -> OpenSet {
        let mut star = BTreeSet::new();
        star.insert(x.to_string());
        for (a, y) in &self.le_relation {
            if a == x {
                star.insert(y.clone());
            }
        }
        OpenSet { elements: star }
    }

    /// Check if U is an up-set: x in U and x <= y => y in U.
    pub fn is_open(&self, u: &OpenSet) -> bool {
        for x in &u.elements {
            for (a, y) in &self.le_relation {
                if a == x && !u.elements.contains(y) {
                    return false;
                }
            }
        }
        true
    }
}

/// A Cover conforming to `urn:omega:math:cover:v0.1.0`.
///
/// An indexed family of subsets of base space X whose union is X.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Cover {
    pub base_space_id: String,
    pub base_space: BTreeSet<String>,
    pub cover_indices: Vec<String>,
    pub subsets: BTreeMap<String, OpenSet>,
}

impl Cover {
    pub fn new(
        base_space_id: impl Into<String>,
        base_space: impl IntoIterator<Item = impl Into<String>>,
        subsets_map: impl IntoIterator<Item = (impl Into<String>, OpenSet)>,
    ) -> Result<Self, String> {
        let base_space_id = base_space_id.into();
        let base_space: BTreeSet<String> = base_space.into_iter().map(Into::into).collect();
        let mut cover_indices = Vec::new();
        let mut subsets = BTreeMap::new();

        for (idx, set) in subsets_map {
            let idx_str = idx.into();
            if set.is_empty() {
                return Err(format!("Cover subset for index '{idx_str}' is empty"));
            }
            if !set.elements.is_subset(&base_space) {
                return Err(format!(
                    "Cover subset for index '{idx_str}' contains elements outside base space"
                ));
            }
            cover_indices.push(idx_str.clone());
            subsets.insert(idx_str, set);
        }

        if cover_indices.is_empty() {
            return Err("Cover indices cannot be empty".to_string());
        }

        // Sort indices lexicographically and check uniqueness
        cover_indices.sort();
        cover_indices.dedup();
        if cover_indices.len() != subsets.len() {
            return Err("Duplicate cover indices detected".to_string());
        }

        // Check union equals base space
        let mut union_set = BTreeSet::new();
        for s in subsets.values() {
            union_set.extend(s.elements.clone());
        }
        if union_set != base_space {
            return Err("Union of subsets does not equal base space".to_string());
        }

        Ok(Self {
            base_space_id,
            base_space,
            cover_indices,
            subsets,
        })
    }

    /// Canonical serialization matching `cover.contract.yaml`:
    /// Cover index identifiers separated by U+001E.
    /// Subsets separated by U+001F with 2-byte little-endian length prefixes for each point.
    pub fn canonical_serialization(&self) -> Vec<u8> {
        let mut out = Vec::new();
        // Indices separated by U+001E
        for (i, idx) in self.cover_indices.iter().enumerate() {
            if i > 0 {
                out.extend("\u{001E}".as_bytes());
            }
            out.extend(idx.as_bytes());
        }
        out.extend(b"|");
        // Subsets separated by U+001F
        for (i, idx) in self.cover_indices.iter().enumerate() {
            if i > 0 {
                out.extend("\u{001F}".as_bytes());
            }
            let set = &self.subsets[idx];
            for elem in &set.elements {
                let bytes = elem.as_bytes();
                let len = bytes.len() as u16;
                out.extend(&len.to_le_bytes());
                out.extend(bytes);
            }
        }
        out
    }

    /// Deterministic SHA-256 hash of canonical serialization.
    pub fn artifact_hash(&self) -> String {
        let bytes = self.canonical_serialization();
        let mut hasher = Sha256::new();
        hasher.update(&bytes);
        format!("{:x}", hasher.finalize())
    }

    /// Build the Nerve of the cover: a simplicial complex where a k-simplex
    /// exists for each set of k+1 cover indices with non-empty intersection.
    pub fn compute_nerve(&self) -> Result<SimplicialComplex, String> {
        let n = self.cover_indices.len();
        let mut maximal_simplices = Vec::new();

        // Check intersections up to max size
        for k in 1..=(1 << n) - 1 {
            let mut subset_indices = Vec::new();
            for i in 0..n {
                if (k & (1 << i)) != 0 {
                    subset_indices.push(i);
                }
            }
            if subset_indices.is_empty() {
                continue;
            }

            // Compute intersection
            let mut inter = self.subsets[&self.cover_indices[subset_indices[0]]].clone();
            for &idx in &subset_indices[1..] {
                inter = inter.intersection(&self.subsets[&self.cover_indices[idx]]);
            }

            if !inter.is_empty() {
                // In nerve, this forms a simplex on vertex set subset_indices
                let oriented = OrientedSimplex::from_unordered(subset_indices)
                    .map_err(|e| format!("Nerve simplex error: {e:?}"))?;
                maximal_simplices.push(oriented);
            }
        }

        SimplicialComplex::from_maximal_simplices(maximal_simplices)
            .map_err(|e| format!("Nerve complex build error: {e:?}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_alexandrov_upset_property() {
        let top = PosetTopology::new(vec!["0", "1", "01"], vec![("0", "01"), ("1", "01")]);
        let star_0 = top.minimal_open_neighborhood("0");
        assert!(star_0.contains("0"));
        assert!(star_0.contains("01"));
        assert!(top.is_open(&star_0));

        let non_open = OpenSet::new(vec!["0"]);
        assert!(!top.is_open(&non_open));
    }

    #[test]
    fn test_cover_validation_and_nerve() {
        let u1 = OpenSet::new(vec!["p1", "p2"]);
        let u2 = OpenSet::new(vec!["p2", "p3"]);
        let cover = Cover::new(
            "space_1",
            vec!["p1", "p2", "p3"],
            vec![("U1", u1), ("U2", u2)],
        )
        .unwrap();

        assert_eq!(cover.cover_indices, vec!["U1", "U2"]);
        let nerve = cover.compute_nerve().unwrap();
        // Since U1 and U2 intersect at p2, there is a 1-simplex between them!
        assert_eq!(nerve.count(0), 2);
        assert_eq!(nerve.count(1), 1);
    }
}
